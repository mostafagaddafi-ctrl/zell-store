-- =====================================================================
-- 0010 — المجموعات (Collections v1)
--
--  الحالة: مسودة للمراجعة — **لم تُنفّذ على أي محرّك**
--  الترتيب: 0007 ← 0008 ← 0008a ← 0009 ← 0010
--
--  بتعمل:
--    (1) جدول collections.
--    (2) جدول product_collections — علاقة متعدد-لمتعدد.
--    (3) RLS + صلاحيات service_role بس (زي كل جداول المشروع).
--    (4) zell_reorder_collections       — ترتيب ذرّي.
--    (5) zell_set_collection_products   — ربط المنتجات ذرّيًا.
--
--  ✅ **idempotent**: كل الجداول والفهارس if not exists، والدوال
--     create or replace (توقيعات جديدة، مفيش قديم يتشال)، والقيود
--     بتتضاف داخل الـcreate نفسه.
--
--  ⚠️ **لازم تتنفّذ بدور postgres** — زي 0008 و0009.
--
--  ⚠️ **مفيش RLS policies عن قصد.** كل جداول المشروع RLS مفعّلة
--     وبلا أي policy، والصلاحيات لـservice_role بس — والمتجر واللوحة
--     الاتنين بيقرأوا من السيرفر بمفتاح service_role. أي policy لـanon
--     هنا كانت هتفتح الجدول للمتصفح من غير داعي. (متحقَّق من
--     pg_policies: صفر policies على المشروع كله.)
--
--  ⚠️ **id بـ identity مش bigserial.** مع identity الصلاحية على
--     الجدول كافية للإدخال؛ bigserial كان هيحتاج grant usage منفصل
--     على الـsequence، وهي خطوة يسهل نسيانها فيفشل الإدخال بعد النشر.
--
--  ⚠️ ليه advisory lock في zell_set_collection_products: نفس درس 0009.
--     FOR UPDATE بيقفل صفوف موجودة، ومجموعة جديدة مالهاش أي روابط —
--     فمجموعة فاضية = مفيش قفل = سباق بين تعديلين متزامنين.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- (0) حارس الدور — قبل أي تعديل
-- ---------------------------------------------------------------------
do $guard$
begin
  if current_user <> 'postgres' then
    raise exception
      'ZELL_MIGRATION_0010_WRONG_ROLE: current_user=% — لازم postgres عشان الملكية ماتتغيّرش',
      current_user;
  end if;
end
$guard$;

-- ---------------------------------------------------------------------
-- (1) collections
-- ---------------------------------------------------------------------
create table if not exists public.collections (
  id          bigint generated by default as identity primary key,
  slug        text        not null,
  title_ar    text        not null,
  subtitle_ar text,
  is_visible  boolean     not null default true,
  sort_order  integer     not null default 0,
  created_at  timestamptz not null default pg_catalog.now(),
  updated_at  timestamptz not null default pg_catalog.now(),

  constraint collections_slug_unique unique (slug),

  -- slug بيظهر في URL، فالشكل مقيّد: حروف صغيرة وأرقام وشرطات بس،
  -- ومابيبدأش ومابينتهيش بشرطة، ومفيش شرطتين ورا بعض.
  constraint collections_slug_format
    check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  constraint collections_slug_length
    check (pg_catalog.length(slug) >= 2 and pg_catalog.length(slug) <= 60),

  constraint collections_title_not_blank
    check (pg_catalog.btrim(title_ar) <> ''),
  constraint collections_title_length
    check (pg_catalog.length(title_ar) <= 80),
  constraint collections_subtitle_length
    check (subtitle_ar is null or pg_catalog.length(subtitle_ar) <= 200),

  constraint collections_sort_order_check check (sort_order >= 0)
);

create index if not exists collections_sort_idx
  on public.collections (sort_order, id);

-- ---------------------------------------------------------------------
-- (2) product_collections — المنتج ينفع يبقى في أكتر من مجموعة
-- ---------------------------------------------------------------------
create table if not exists public.product_collections (
  collection_id bigint      not null references public.collections(id) on delete cascade,
  product_id    integer     not null references public.products(id)    on delete cascade,
  sort_order    integer     not null default 0,
  created_at    timestamptz not null default pg_catalog.now(),

  primary key (collection_id, product_id),
  constraint product_collections_sort_order_check check (sort_order >= 0)
);

-- للسؤال العكسي: المنتج ده في أنهي مجموعات؟
create index if not exists product_collections_product_idx
  on public.product_collections (product_id);

-- ---------------------------------------------------------------------
-- (3) RLS + الصلاحيات
-- ---------------------------------------------------------------------
alter table public.collections         enable row level security;
alter table public.product_collections enable row level security;

revoke all on table public.collections         from public, anon, authenticated;
revoke all on table public.product_collections from public, anon, authenticated;

grant select, insert, update, delete on table public.collections         to service_role;
grant select, insert, update, delete on table public.product_collections to service_role;

-- ---------------------------------------------------------------------
-- (4) الترتيب الذرّي — مرآة zell_reorder_products
--     بيكتب sort_order من ١، وبيرفض أي مجموعة مش مساوية لكل الصفوف.
-- ---------------------------------------------------------------------
create or replace function public.zell_reorder_collections(p_ids bigint[])
returns integer
language plpgsql
set search_path to ''
as $function$
declare
  actual_count  integer;
  updated_count integer;
begin
  if p_ids is null or pg_catalog.array_length(p_ids, 1) is null then
    raise exception 'ZELL_INVALID_ORDER';
  end if;

  if (select pg_catalog.count(distinct id) from pg_catalog.unnest(p_ids) id)
     <> pg_catalog.array_length(p_ids, 1) then
    raise exception 'ZELL_INVALID_ORDER';
  end if;

  select pg_catalog.count(*) into actual_count from public.collections;
  if actual_count <> pg_catalog.array_length(p_ids, 1)
     or exists (select 1 from public.collections c where not (c.id = any(p_ids))) then
    raise exception 'ZELL_INVALID_ORDER';
  end if;

  update public.collections c
  set sort_order = o.ord, updated_at = now()
  from pg_catalog.unnest(p_ids) with ordinality o(id, ord)
  where c.id = o.id;

  get diagnostics updated_count = row_count;
  return updated_count;
end;
$function$;

-- ---------------------------------------------------------------------
-- (5) ربط المنتجات بمجموعة — استبدال كامل للقائمة، ذرّيًا
--     بترجّع عدد الروابط بعد التعديل، أو null لو المجموعة مش موجودة.
-- ---------------------------------------------------------------------
create or replace function public.zell_set_collection_products(
  p_collection_id bigint,
  p_product_ids   integer[]
) returns integer
language plpgsql
set search_path to ''
as $function$
declare
  v_ids   integer[] := coalesce(p_product_ids, '{}'::integer[]);
  v_len   integer   := coalesce(pg_catalog.array_length(v_ids, 1), 0);
  v_count integer;
begin
  if p_collection_id is null then
    raise exception 'ZELL_INVALID_COLLECTION';
  end if;

  -- ⚠️ القفل بالمجموعة نفسها مش بصفوفها — مجموعة لسه مالهاش روابط
  --    مفيش فيها صفوف يقفلها FOR UPDATE (نفس حالة أول رفعة في 0009).
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('zell_set_collection_products:' || p_collection_id::text, 0)
  );

  if not exists (select 1 from public.collections where id = p_collection_id) then
    return null;
  end if;

  -- تكرار في القائمة
  if (select pg_catalog.count(distinct id) from pg_catalog.unnest(v_ids) id) <> v_len then
    raise exception 'ZELL_INVALID_COLLECTION_PRODUCTS';
  end if;

  -- منتج مش موجود — الـFK كان هيكشفها، بس الرسالة دي أوضح
  if exists (
    select 1 from pg_catalog.unnest(v_ids) id
    where not exists (select 1 from public.products p where p.id = id)
  ) then
    raise exception 'ZELL_INVALID_COLLECTION_PRODUCTS';
  end if;

  -- اللي اتشال من القائمة. مع قائمة فاضية: = any('{}') = false،
  -- فالـnot بيبقى true وكل الروابط بتتشال — وده المقصود.
  delete from public.product_collections pc
  where pc.collection_id = p_collection_id
    and not (pc.product_id = any(v_ids));

  insert into public.product_collections (collection_id, product_id, sort_order)
  select p_collection_id, o.id, o.ord
  from pg_catalog.unnest(v_ids) with ordinality o(id, ord)
  on conflict (collection_id, product_id)
    do update set sort_order = excluded.sort_order;

  select pg_catalog.count(*) into v_count
  from public.product_collections where collection_id = p_collection_id;

  update public.collections set updated_at = now() where id = p_collection_id;

  return v_count;
end;
$function$;

-- ---------------------------------------------------------------------
-- (6) صلاحيات الدوال
-- ---------------------------------------------------------------------
revoke all on function public.zell_reorder_collections(bigint[])
  from public, anon, authenticated;
grant execute on function public.zell_reorder_collections(bigint[])
  to service_role;

revoke all on function public.zell_set_collection_products(bigint, integer[])
  from public, anon, authenticated;
grant execute on function public.zell_set_collection_products(bigint, integer[])
  to service_role;

-- ---------------------------------------------------------------------
-- (7) تحقق ذاتي
-- ---------------------------------------------------------------------
do $verify$
declare
  v_name   text;
  v_config text[];
  v_owner  text;
  v_sig    text;
begin
  -- الجدولين موجودين وRLS مفعّلة
  foreach v_name in array array['collections', 'product_collections'] loop
    if not exists (
      select 1 from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid = c.relnamespace
      where n.nspname = 'public' and c.relname = v_name and c.relrowsecurity
    ) then
      raise exception 'ZELL_MIGRATION_0010_RLS_OFF: %', v_name;
    end if;

    if pg_catalog.has_table_privilege('anon', 'public.' || v_name, 'select')
       or pg_catalog.has_table_privilege('authenticated', 'public.' || v_name, 'select') then
      raise exception 'ZELL_MIGRATION_0010_PUBLIC_SELECT: %', v_name;
    end if;

    if not pg_catalog.has_table_privilege('service_role', 'public.' || v_name, 'select') then
      raise exception 'ZELL_MIGRATION_0010_MISSING_SELECT: %', v_name;
    end if;
  end loop;

  -- الدالتين: تعريف واحد لكل واحدة، search_path، المالك، الصلاحيات
  foreach v_sig in array array[
    'public.zell_reorder_collections(bigint[])',
    'public.zell_set_collection_products(bigint, integer[])'
  ] loop
    select p.proconfig, pg_catalog.pg_get_userbyid(p.proowner)
    into v_config, v_owner
    from pg_catalog.pg_proc p
    where p.oid = v_sig::regprocedure;

    if v_config is null or not ('search_path=""' = any(v_config)) then
      raise exception 'ZELL_MIGRATION_0010_SEARCH_PATH: % %', v_sig, v_config;
    end if;

    if v_owner <> 'postgres' then
      raise exception 'ZELL_MIGRATION_0010_OWNER: % owner=%', v_sig, v_owner;
    end if;

    if pg_catalog.has_function_privilege('anon', v_sig, 'execute')
       or pg_catalog.has_function_privilege('authenticated', v_sig, 'execute') then
      raise exception 'ZELL_MIGRATION_0010_ANON_EXECUTE: %', v_sig;
    end if;

    if not pg_catalog.has_function_privilege('service_role', v_sig, 'execute') then
      raise exception 'ZELL_MIGRATION_0010_MISSING_EXECUTE: %', v_sig;
    end if;
  end loop;

  -- قيد الـslug بيرفض الشكل الغلط فعلًا
  if 'Bad Slug' ~ '^[a-z0-9]+(-[a-z0-9]+)*$' then
    raise exception 'ZELL_MIGRATION_0010_SLUG_REGEX_BROKEN';
  end if;
end
$verify$;

notify pgrst, 'reload schema';

commit;

